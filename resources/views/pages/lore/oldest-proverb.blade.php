<h1>The Oldest Proverb</h1>

<p class="display-5">He who controls the monsters,<br/>controls the anthropes.</p>

<p>It’s the oldest proverb in the world. Nobody can claim who said it first; a version of it exists in almost every culture and language. It’s a philosophy that has lead to wars, horrific experimentation, and genocide. Entire religions and universities developed around it.</p>

<p>The idea is simple, yet open to a depth of interpretation. Some see it simply meaning physical control of monsters, such as breeding and regulation. Others see a metaphysical meaning.</p>

<p>Some interpret it as a call for anthropes to understand and master the monstrous aspects within themselves, suggesting that by doing so, they can achieve greater self-awareness and control over our own nature.</p>

