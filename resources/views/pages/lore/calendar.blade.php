<p>The Great Agreement creates the calendar and standards of time for the major nations of the world. Under the Great Agreement Calendar, the year begins at the northern spring equinox and is divided into seasonal cycles of 13 weeks of 7 days a week, with any leap days accumulated until they add up to an extra week.</p> 

<ul>
<li>Spring: 91 days</li>
<li>Summer: 91 days</li>
<li>Autumn: 91 days</li>
<li>Winter: 91 or 98 days.</li>
</ul>    

<p>In modern societies, the week is typically divided into five days of work and two days of rest.</p>

<h2>Notation</h2>

<p>Dates are typically written in the format <strong>YYYY.S.WW.D</strong>, where <strong>YYYY</strong> is the year, <strong>S</strong> is the season number (1-4), <strong>WW</strong> is the week number within the season (01-13), and <strong>D</strong> is the day of the week (1-7).</p>

<h2>History</h2>
<p>Prior to the Great Agreement, different nations and cultures used different calendars, making international relations and trade difficult. The Great Agreement established a standardized calendar system to facilitate communication and cooperation among nations.</p>

<p>At the time of the Great Agreement, scholars of anthrope history had establsihed that the earliest civilzations with recorded histories had emerged approximately 5,300 years prior. To create a unified calendar, the Great Agreement established a new epoch,    fixing the year of ratification and implementation as year 6000.(*) This gave all nations, tribes and clans a common reference point, and the Great Agreement encouraged all peoples to map their histories onto the new calandar.</p>

<p>(*) The continents of <a href="/Erebis">Erebis</a> and <a href="/Asis">Asis</a> saw the Great Agreement ratified in the year numbered as 6000. However, the process of ratifying the Great Agreement took longer in <a href="/Pluralis">Pluralis</a>, which did not ratify it until the following year.</p>

<p>Some cultures and nations chose to retain their own traditional calendars for cultural or religious reasons, but the Great Agreement's quickly calendar became the standard for international relations and trade. And with its adoption came many benefits.</p>

<p>Historians cite the calendar as one of the most effective tools in bringing about the goals of the Great Agreement: peace, cooperation, and mutual prosperity among the world's nations. For one, it was one of the esaiest things for differing peoples to accept as a common standard. </p>

<p>The calendar did <em>not</em> require anyone to abandon their existing cultural or religious calendars. Instead, it functioned as a <em>civil</em> calendar for everyday use. The diplomats who implemented the Great Agreement encouraged nations to map their cultural and traditional observances to the new calendar, and met little resistance in doing so.</p>

