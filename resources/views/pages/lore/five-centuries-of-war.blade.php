<h3>North and South America</h3>

<p>During this time, North and South America become major theaters of conflict as well. The northern superpower from Europe invades North America from Greenland via Iceland, while the Asian superpower invades from Siberia. The two superpowers clash in Canada, running over American tribes in the process. The hostilities between the two superpowers bleed back over to their respective continents, and a bloody war rages in the Near East.</p>

<p>The anthrope population of North and South America fell by half during the Five Centuries of War.  The invasions by outsiders and internal conflicts separated the people into two broad groups. Those that were more developed and more cosmopolitan drew to the coasts and the Great Lakes. Less-developed tribes and clans retreated into the interior and migrated south towards the jungles.</p>

Tribes and loosely-organized nations that had occupied large regions of land coalesced around the coasts, major rivers and Great Lakes.

<h2>Pogroms and Genocide</h2>


<p>The Five Centuries of War are characterized by numerous pogroms against certain races, particularly those perceived as extraordinarily powerful.</p>

<p>Races with wings were particularly targeted for persecution, as people perceived them (both naturally and through propaganda campaigns) to be capable of conquering all of anthrope civilization.</p>

<p>The pogroms resulted in the extinction of several races and drove several other races into isolation. Monstrous anthropes disappeared from the developed peoples under the belief that their monstrosity made them more of a target.</p>

<h2>Advances in Technology</h2>

<p>The Five Centuries of War saw profound innovations in the breeding and training of monsters. Warring nations used specific breeding techniques to produce and accumulate monsters for war. Those nations that experienced liberty from war, no matter how fleeting, took advantage of emerging technology in heavy industry. The nations of North and South America had particular success in transitioning monster husbandry from agriculture to industry.</p>

