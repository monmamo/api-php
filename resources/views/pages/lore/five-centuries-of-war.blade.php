<h1>The Five Centuries of War</h1>

<p>The "Five Centuries of War" is the name given to a prolonged period of conflict and upheaval that spanned approximately five centuries years in anthrope history, roughly from the 55th-60th centuries. There is no definite beginning or end to the Five Centuries of War; rather, the time is characterized by a series of significant conflicts and events that collectively define this era. There is a general consensus among historians about which wars and conflicts are "officially" part of the Five Centuries of War, and those conflicts actually span almost to six centuries.</p>


