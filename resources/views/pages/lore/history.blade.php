<h2>Five Centuries of War (centuries 55-60)</h2>

<p>As kingdoms grow, conflict is inevitable. The Age of Kingdoms gives way to the Five Centuries of War, a prolonged period of conflict that engulfs much of the known world. The wars are characterized by shifting alliances, territorial disputes, and the rise and fall of powerful empires.</p>

<p>The time period is marked by substantial migration and conquest of powers across the continents:</p>

<ul>
    <li>Asians invade America from Siberia.</li>
    <li>Europeans invade America from Greenland via Iceland.</li>
    <li>The two superpowers clash in Canada, running over American tribes in the process.</li>
    <li>The hostilities between the two superpowers bleeds back over to their respective continents, and a bloody war rages in the Near East.</li>
</ul>

<h2>The Great Agreement (century 60-61)</h2>

<ul>
    <li>It took about forty years to bring the Great Agreement from proposal to ratification, signature and implementation.</li>
    <li>Even after the Great Agreement, some tribes in the incorporated lands resisted the new arrangement and continued to wage war decades after the implementation of the Great Agreement. This ongoing fighting resulted in the destruction and dispersal of some tribes.</li>
    <li>In <a href="#">Pluralis</a>, some dissenters migrated to the interior. But many fled to the jungles of the <a href="#">County of the Isthmus</a> and the <a href="#">Southern Continent (Pluralis)</a>, where they integrated with native tribes and peoples. As a result, the <a href="#">Northern Continent (Pluralis)</a> developed into a representative republic, and populated areas coalesced into <a href="#">counties</a>. But in the jungles, civilization manifested as a massive network of villages.</li>
</ul>
