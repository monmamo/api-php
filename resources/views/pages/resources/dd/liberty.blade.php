<h1>Path of Liberty (Chaotic Good)</h1>


<p>A chaotic good anthrope acts as his conscience directs him with little regard for what others expect of him. He makes his own way, but he's kind and benevolent. He believes in goodness and right but has little use for laws and regulations. He hates it when people try to intimidate others and tell them what to do. He follows his own moral compass, which, although good, may not agree with that of society.</p>

<p>A chaotic good organization values freedom and flexibility but also strives to do good. It champions individual rights and allows its members considerable latitude in how they pursue the organization's goals.</p>

<p>Chaotic good is the best alignment you can be because it combines a good heart with a free spirit.</p>

<p>Chaotic good can be a dangerous alignment when it disrupts the order of society and punishes those who do well for themselves.</p>

