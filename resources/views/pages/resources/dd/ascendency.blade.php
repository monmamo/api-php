<h1>Path of Ascendency (Lawful Evil)</h1>


<p>A lawful evil anthrope methodically takes what he wants within the limits of his code of conduct without regard for whom it hurts. He cares about tradition, loyalty, and order but not about freedom, dignity, or life. He plays by the rules but without mercy or compassion. He is comfortable in a hierarchy and would like to rule, but is willing to serve. He condemns others not according to their actions but according to race, religion, homeland, or social rank. He is loath to break laws or promises.</p>

<p>A lawful evil organization is structured and methodical in its pursuit of evil. It has clear rules, a defined chain of command, and established procedures. It expects all members to uphold its standards without exception. It is dedicated to spreading evil, oppressing the innocent, and furthering the organization's power and influence.</p>

<p>The reluctance to break laws or promises comes partly from the lawful nature and partly because the lawful anthrope or organization depends on order to protect themselves from those who oppose them on moral grounds. Some lawful evil villains have particular taboos, such as not killing in cold blood (but having underlings do it) or not letting children come to harm (if it can be helped). They imagine that these compunctions put them above unprincipled villains.</p>

<p>Some lawful evil anthropes and organizations commit themselves to evil with a zeal like that of a crusader committed to good. Beyond being willing to hurt others for their own ends, they take pleasure in spreading evil as an end unto itself. They may also see doing evil as part of a duty to an evil deity or master.</p>

<p>Lawful evil anthropes and organizations consider their alignment to be the best because it combines honor with a dedicated self-interest.</p>

<p>Lawful evil is the most dangerous alignment because it represents methodical, intentional, and frequently successful evil.</p>

