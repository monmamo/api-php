<h1>Path of Integrity (Lawful Good)</h1>


<p>A lawful good anthrope acts as a good anthrope is expected or required to act. He combines a commitment to oppose evil with the discipline to fight relentlessly. He tells the truth, keeps his word, helps those in need, and speaks out against injustice. A lawful good anthrope hates to see the guilty go unpunished.</p>

<p>A lawful good organization places the welfare of its members and the society it serves above all else. It has a strict code of conduct and expects all members to uphold it without exception. It is dedicated to justice, protection of the innocent, and the eradication of evil.

<p>Lawful good is the best alignment you can be because it combines honor and compassion.</p>

<p>Lawful good can be a dangerous alignment when it restricts freedom and criminalizes self-interest.</p>

