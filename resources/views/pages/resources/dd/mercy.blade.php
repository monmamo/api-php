<h1>Path of Mercy (Neutral Good)</h1>


<p>A neutral good anthrope does the best that a good anthrope can do. He is devoted to helping others. He works with kings and magistrates but does not feel beholden to them.</p>

<p>A neutral good organization is dedicated to doing good without bias for or against order. It helps those in need and protects the innocent without regard for rules, traditions, or loyalties.</p>

<p>Neutral good is the best alignment you can be because it means doing what is good without bias for or against order.</p>

<p>Neutral good can be a dangerous alignment when it advances mediocrity by limiting the actions of the truly capable.</p>


