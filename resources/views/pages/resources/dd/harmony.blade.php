<h1>Path of Harmony (Lawful Neutral)</h1>


<p>A lawful neutral anthrope acts as law, tradition, or a personal code directs her. Order and organization are paramount to her. She may believe in personal order and live by a code or standard, or she may believe in order for all and favor a strong, organized government.</p>

<p>A lawful neutral organization values structure, order, and predictability above all else. It has clear rules, a defined chain of command, and established procedures. It expects all members to uphold its standards without exception.</p>

<p>Lawful neutral is the best alignment you can be because it means you are reliable and honorable without being a zealot.</p>

<p>Lawful neutral can be a dangerous alignment when it seeks to eliminate all freedom, choice, and diversity in society.</p>

