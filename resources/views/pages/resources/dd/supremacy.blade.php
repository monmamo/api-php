<h1>Path of Supremacy (Neutral Evil)</h1>


<p>A neutral evil anthrope or organization does whatever they can get away with. They are out for themselves. They shed no tears for those they kill, whether for profit, sport, or convenience. They have no love of order and hold no illusion that following laws, traditions, or codes would make them any better or more noble. On the other hand, they don't have the restless nature or love of conflict that a chaotic evil anthrope or organization would have.</p>

<p>Some neutral evil anthropes and organizations hold up evil as an ideal, committing evil for its own sake. Most often, such villains are devoted to evil deities or secret societies.</p>
    
<p>Neutral evil anthropes and organizations consider their alignment to be the best because they can advance themselves without regard for others.</p>

<p>Neutral evil is the most dangerous alignment because it represents pure evil without honor and without variation.</p>

