<h1>Path of Autonomy (Chaotic Neutral)</h1>


<p>A chaotic neutral anthrope follows his whims. He is an individualist first and last. He values his own liberty but doesn't strive to protect others' freedom. He avoids authority, resents restrictions, and challenges traditions. A chaotic neutral anthrope does not intentionally disrupt organizations as part of a campaign of anarchy. To do so, he would have to be motivated either by good (and a desire to liberate others) or evil (and a desire to make those different from himself suffer). A chaotic neutral anthrope may be unpredictable, but his behavior is not totally random. He is not as likely to jump off a bridge as to cross it.</p>

<p>A chaotic neutral organization values freedom and flexibility above all else. It has few rules, a flexible chain of command, and adaptable procedures. It allows its members considerable latitude in how they pursue the organization's goals.</p>

<p>Chaotic neutral is the best alignment you can be because it represents true freedom from both society's restrictions and a do-gooder's zeal.</p>

<p>Chaotic neutral can be a dangerous alignment when it seeks to eliminate all authority, harmony, and order in society.</p>

