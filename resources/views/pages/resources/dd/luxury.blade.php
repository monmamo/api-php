<h1>Path of Luxury (Chaotic Evil)</h1>


<p>A chaotic evil anthrope or organization does whatever their greed, hatred, and lust for destruction drive them to do. They are hot-tempered, vicious, arbitrarily violent, and unpredictable. If they are simply out for whatever they can get, they are ruthless and brutal. If they are committed to the spread of evil and chaos, they are even worse. Thankfully, their plans are haphazard, and any groups they join or form are poorly organized. Typically, chaotic evil people can be made to work together only by force, and their leader lasts only as long as they can thwart attempts to topple or assassinate them.</p>

<p>Chaotic evil anthropes and organizations believe their alignment is the best because it combines self-interest and pure freedom.</p>

<p>Chaotic evil is the most dangerous alignment because it represents the destruction not only of beauty and life but also of the order on which beauty and life depend.</p>

