<h1>Path of Equity (True Neutral)</h1>


<p>A neutral anthrope does what seems to be a good idea. She doesn't feel strongly one way or the other when it comes to good vs. evil or law vs. chaos. Most neutral anthropes exhibit a lack of conviction or bias rather than a commitment to neutrality. Such a anthrope thinks of good as better than evil-after all, she would rather have good neighbors and rulers than evil ones. Still, she's not personally committed to upholding good in any abstract or universal way.</p>

<p>Some neutral anthropes, on the other hand, commit themselves philosophically to neutrality. They see good, evil, law, and chaos as prejudices and dangerous extremes. They advocate the middle way of neutrality as the best, most balanced road in the long run.</p>

<p>A neutral organization takes a balanced approach to law and chaos as well as good and evil. It values order and freedom equally and seeks to balance the two in its structure and procedures. It helps those in need but does so without bias for or against law or chaos.</p>

<p>Neutral is the best alignment you can be because it means you act naturally, without prejudice or compulsion.</p>

<p>Neutral can be a dangerous alignment when it represents apathy, indifference, and a lack of conviction.</p>

