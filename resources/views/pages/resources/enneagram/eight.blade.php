<h1>Eight: The Challenger, the Protector, the Leader</h1>

<p>Eights are self-confident, decisive, and willful. They are natural leaders, protective, resourceful, and straight-talking, but can also be domineering and confrontational. They typically have problems with their tempers and with allowing themselves to be vulnerable. At their best, Eights are magnanimous and inspiring—able to bring people together to accomplish great things.</p>

    <ul>
        <li>Basic Fear: Of being harmed or controlled by others.</li>
        <li>Basic Desire: To protect themselves and determine their own course in life.</li>
    </ul>

<h2>Positive Arc: Intensity to Innocence</h2>

<p>Eights at their best represent boldness and decisiveness. At their worst, they come across as domineering and combative. Their core vice is a lust to experience intensity in every moment of their lives, as a way to escape their own fears and deny their own weaknesses.</p>

<p>The deep-seated Lie of their personality is fueled by the unconscious fear that they might experience helplessness under the the control or betrayal of someone else. Their arc challenges them to return to the trusting innocence of their lost childhoods. When healthy, they offer the gift of being able to stand up for not just themselves but for all those who need a protector.</p>

<h2>Negative Arc: Intensity to Violence</h2>

<p>Type Eights’ native desire to feel protected and self-sovereign can become complicated by the unconscious fear that they are vulnerable to being controlled or harmed by others. Defensively, these characters push back as a way of feeling their own strength and invulnerability. If unchecked, this desire to feel safe via the intensity of their own experiences can devolve into reflexive aggression. An early sign this character may be at the beginning of an arc (whether positive or negative) is the tendency to try to forcefully control everything and everyone in their lives.</p>

<p>This may lead them further into the Lie that they must struggle in order to accomplish anything. If these tendencies are left unchecked, Eights may begin manipulating others by exerting dominance over them and using force (even if just the force of intense personality) to get others to comply with their demands. In cases of extreme unhealth, they may end up projecting their fear of being harmed or controlled onto the world around them, in turn bullying others into submission.</p>

