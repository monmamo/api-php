<h1>Nine: The Peacemaker, the Mediator, the Healer</h1>

<p>Nines are easygoing, self-effacing, and receptive. They are natural peacemakers, empathetic, supportive, and adaptive, but can also be complacent and stubborn. They typically have problems with inertia and with asserting themselves. At their best, Nines are spiritually aware and able to bring harmony to even the most difficult situations.</p>

    <ul>
        <li>Basic Fear: Of loss and separation.</li>
        <li>Basic Desire: To maintain inner stability and peace of mind.</li>
    </ul>

<h2>Positive Arc: Resignation to Right Action</h2>

<p>Nines at their best represent tranquility and reliability. At their worst, they come across as passive-aggressive and apathetic. Their core vice is a resignation to their lot, a desire to remove themselves from the struggle of life, out of a belief that they cannot truly impact it for the good of themselves or others.</p>

<p>The deep-seated Lie of their personality is fueled by the unconscious fear that in taking certain stands (both internally and externally), they risk feeling disconnected and adrift from others. Their arc challenges them to rise into a discernment of and ability to take “right action” on behalf of themselves and others. When healthy, they offer the gift of bringing peace and healing to the world around them.</p>

<h2>Negative Arc: Apathy to Disassociation</h2>

<p>Type Nines’ native desire to be at peace with everyone and everything can become complicated by an unconscious fear that they are, in fact, irreparably separate from others. Defensively, these characters sink into lethargy and apathy as a means of avoiding the pain of conflict. If unchecked, this desire to avoid conflict can devolve into a failure to stand up for themselves or issues they believe in. An early sign this character may be at the beginning of an arc (whether positive or negative) is the tendency to avoid allowing themselves to feel impacted or affected by their experiences of the world.</p>

<p>This may lead them further into the Lie that in order to avoid the further separation they feel when in disagreement with others, they should suppress their own needs and identities to avoid conflict. If these tendencies are left unchecked, Nines may begin manipulating others through passive resistance and by ignoring the realities of certain situations. In cases of extreme unhealth, they may end up projecting the fear that they will lose connection with others onto the world around them, in turn cutting off connection with those who love them.</p>

