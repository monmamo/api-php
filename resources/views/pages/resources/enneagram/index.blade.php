<h2 id="centers-of-intelligence">Centers of Intelligence</h2>

<h3 id="gut">the gut (instinctive)</h3>

        <ul>
            <li>concerned with justice</li>
            <li>seeking autonomy</li>
            <li>underlying issue: wrath</li>
            <li><strong>Advice:</strong> Instead of acting quickly based on your instincts, allow yourself to think first. Think about how your anger (which is likely the deep underlying cause of your instinctual reaction) affects you and those around you.</li>
        </ul>

        <h3 id="heart">the heart (feeling)</h3>
        <ul>
            <li>concerned with image</li>
            <li>seeking attention</li>
            <li>underlying issue: shame</li>
            <li><strong>Advice:</strong> Instead of acting quickly based on your feelings, allow yourself to think first. Think about how your shame (which is likely the deep underlying cause of your feeling reaction) affects you and those around you.</li>
        </ul>

        <h3 id="head">the head (thinking)</h3>
        <ul>
            <li>concerned with strategies</li>
            <li>seeking security</li>
            <li>underlying issue: fear</li>
            <li><strong>Advice:</strong> Instead of acting based on your thinking, allow yourself to "be" first. Think about how your fear/anxiety (which is likely the deep underlying cause of your thinking reaction) affects you and those around you. Don't let that fear stop you from being your actual self with others.</li>
        </ul>

        <h2 id="harmony-groups">Harmony Groups</h2>

        <p>Shows us how each of these three groups relate to the world.</p>

<h3>idealist, frustration</h3>
<ul>
    <li>Has an idea of how the world around them should be, and becomes frustrated when the world is not that way.</li>
    <li><strong>Advice:</strong> Learn to let go of your frustration when the world doesn't match your ideal and embrace the world for what it is.</li>
</ul>

<h3>pragmatist, attachment</h3>
<ul>
    <li>Seeks their own place the world, and attach to what makes that work for them pragmatically.</li>
    <li><strong>Advice:</strong> Learn to let go of worldly attachments and allow in discomfort which will allow you to integrate into the higher qualities of the day to day world.</li>
</ul>

<h3>relationist, rejection</h3>
<ul>
    <li>Relates to the world through connection to others, and tried to keep rejection from happening by providing necessary functions.</li>
    <li><strong>Advice:</strong> Learn to let go of your fear of rejection and embrace the natural flow of love and energy.</li>
</ul>

