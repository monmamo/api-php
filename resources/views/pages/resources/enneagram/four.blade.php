<h1>Four: The Individualist, the Romantic, the Artist</h1>


<p>Fours are self-aware, sensitive, and reserved. They are emotionally honest, creative, and personal, but can also be moody and self-conscious. Withholding themselves from others due to feeling vulnerable and defective, they can also feel disdainful and exempt from ordinary ways of living. They typically have problems with melancholy, self-indulgence, and self-pity. At their best, Fours are inspired and highly creative, they are able to renew themselves and transform their experiences.</p>

    <ul>
        <li>Basic Fear: That they have no identity or personal significance.</li>
        <li>Basic Desire: To find themselves and their significance (to create an identity).</li>
    </ul>

<h2>Positive Arc: Envy to Equanimity</h2>

<p>Type Fours at their best represent creativity and idealism. At their worst, they come across as self-absorbed and unrealistic. Their core vice is a painful envy, born out of their sense that they are somehow more deficient than other people or that something essential is missing from their lives.</p>

<p>The deep-seated Lie of their personality is fueled by an unconscious fear that they somehow lack personal identity or significance. Their arc challenges them to accept the beauty and perfection inherent within themselves, so they can recognize their own worth and move into a genuine sense of self-esteem. When healthy, they offer the gift of being able to release the past and live fully in the present.</p>

<h2>Negative Arc: Envy to Self-Obsession</h2>

<p>Type Fours’ native desire to be authentically themselves can become complicated by an unconscious fear that they have no true personal significance or identity. Defensively, these characters then begin to hide behind a victim mentality that leads them to envy the “perfect” lives of others, or to hide behind romantic daydreams about what their lives could be. If unchecked, this envy can devolve into self-indulgence and self-obsession. An early sign this character may be at the beginning of an arc (whether positive or negative) is a tendency to turn inward, refusing to move past injuries and even seeking to intensify their feelings.</p>

<p>This may lead them further into the Lie that they are somehow too special or unique for the rest of the world to ever understand or appreciate. If these tendencies are left unchecked, Fours may begin manipulating others by becoming more and more temperamental, demanding others treat them with kid gloves. In cases of extreme unhealth, they may end up projecting the fear that they are “nobodies” onto the world around them, treating others with disdain.</p>

