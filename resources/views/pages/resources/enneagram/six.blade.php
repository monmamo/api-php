    <h1>Six: The Loyalist, the Skeptic, the Guardian</h1>

<p>Sixes are committed, security-oriented, and reliable. They are hard-working, responsible, and trustworthy, but can also be defensive, evasive, and anxious—running on stress while complaining about it. They typically have problems with self-doubt and suspicion. At their best, Sixes are internally stable and self-reliant, courageously championing themselves and others.</p>

    <ul>
        <li>Basic Fear: Of being without support and guidance.</li>
        <li>Basic Desire: To have security and support.</li>
    </ul>

<h2>Positive Arc: Anxiety to Inner Peace</h2>

<p>Type Sixes at their best represent loyalty and responsibility. At their worst, they come across as reactive and fearful. Their core vice is often talked about as fear, but is really more of a never-ending simmer of often nameless anxiety.</p>

<p>The deep-seated Lie of their personality is fueled by the (actually pretty conscious) fear of being without support or guidance in a dangerous and untrustworthy world. Their arc challenges them to grow into, first, a powerful trust in their own reliability and, second, into a surrendered belief in the inherent goodness of life. When healthy, they offer the gift of true courage and capability in handling life’s challenges.</p>

<h2>Negative Arc: Anxiety to Dogmatism</h2>

<p>Type Sixes’ native desire for safety and security can become complicated by the unconscious fear that they are unable to offer themselves the support and guidance they need in order to feel safe. Defensively, these characters then begin to increasingly rely on external authorities and systems of belief. If unchecked, their anxiety can devolve into a frantic adherence to dogma. An early sign this character may be at the beginning of an arc (whether positive or negative) is the tendency to make themselves dependent on people or systems who are “stronger” than themselves.</p>

<p>This may lead them further into the Lie that they are incapable of thinking for themselves or even taking care of themselves without external aid. If these tendencies are left unchecked, Sixes may begin manipulating others by complaining and testing their loyalties. In cases of extreme unhealth, they may end up projecting their fears onto the world around them, in turn undermining the strength and faith of others, seeking to render them helpless.</p>

