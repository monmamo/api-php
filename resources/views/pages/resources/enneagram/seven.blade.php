    <h1>Seven: The Enthusiast, the Generalist, the Adventurer</h1>

<p>Sevens are spontaneous, versatile, and acquisitive. They are extroverted, optimistic, and fun-loving, but can also be distracted and scattered. They typically have problems with impatience and impulsiveness. At their best, Sevens are committed, focused, and joyful—embracing life’s opportunities with both feet on the ground.</p>

    <ul>
        <li>Basic Fear: Of being deprived and in pain.</li>
        <li>Basic Desire: To be satisfied and content—to have their needs fulfilled.</li>
    </ul>

<h2>Positive Arc: Gluttony to Joy</h2>

<p>Sevens at their best represent optimism and fun. At their worst, they come across as impulsive and undisciplined. Their core vice of “gluttony” refers to an insatiable desire to immerse themselves in experience after experience as a way of distracting themselves from inner fears and pain.</p>

<p>The deep-seated Lie of their personality is fueled by unconscious fears of being deprived, abandoned, or trapped. Their arc challenges them to grow beyond a pursuit of shallow distraction into an embodied joy. When healthy, they offer the gift of sharing this joyful celebration of existence with everyone around them.</p>

<h2>Negative Arc: Gluttony to Escapism</h2>

<p>Type Sevens’ native desire for happiness can become complicated by an unconscious fear that they are, in fact, likely to suffer deprivation or pain. Defensively, these characters fixate on seeking positive experiences (to the point of “gluttony”) and avoiding any and all negative experiences. If unchecked, this desire for fun and abundance can devolve into hedonistic escapism. An early sign this character may be at the beginning of an arc (whether positive or negative) is the tendency to fixate on a happy future (to the exclusion of the past or present) by counting down their lives to the “next good thing.”</p>

<p>This may lead them further into the Lie that their best life is always someplace else, over the horizon, and just out of reach. If these tendencies are left unchecked, Sevens may begin manipulating others by distracting them from “real” issues or from negative situations they do not wish to acknowledge. In cases of extreme unhealth, Sevens may end up projecting their fear of being trapped onto the world around them, in turn making others feel trapped or deprived in some way.</p>

