    <h1>Three: The Achiever, the Performer, the Role Model</h1>

<p>Threes are adaptable, excelling, driven, and image-conscious. They are self-assured, attractive, and charming, ambitious people who can also be status-conscious and highly driven for advancement. They typically have problems with workaholism and competitiveness. At their best, Threes are self-accepting, authentic, and everything they appear to be: role models who inspire others.</p>

    <ul>
        <li>Basic Fear: Of being worthless.</li>
        <li>Basic Desire: To feel valuable and worthwhile.</li>
    </ul>

<h2>Positive Arc: Vanity to Authenticity</h2>

<p>Type Threes at their best represent productivity and adaptability. At their worse, they come across as image-conscious and emotionally out of touch. Their core vice is a misdirected vanity, which they try to hide behind the mask of their accomplishments—a sort of self-deceit designed to cover up their inner sense of inadequacy.</p>

<p>The deep-seated Lie of their personality is fueled by an unconscious fear that their only value lies in their external achievements. Their arc challenges them to grow beyond their over-identification with how they are viewed by others and into a deeply realized authenticity. When healthy, they offer the true gift of bearing witness to the intrinsic value in themselves and others.</p>

<h2>Negative Arc: Vanity to Grandiosity</h2>

<p>Type Threes’ native desire to offer value to the world can become complicated by an unconscious fear that they are, in fact, without inherent value–that their only value is what they do, not who they are. Defensively, these characters then begin to chase after success and external affirmation as a way of pumping up their own self-image. If unchecked, this image-consciousness can devolve into delusions of grandeur. An early sign this character may be at the beginning of an arc (whether positive or negative) is their tendency to hide their authentic selves by trying to become an “ideal.”</p>

<p>This may lead them further into the Lie that they must climb higher and higher on the ladder of power, prestige, and success. If these tendencies are left unchecked, Threes may begin manipulating others by adopting whatever mask will be most acceptable or charming, allowing them to push toward their own end goals. In cases of extreme unhealth, they may end up arrogantly projecting all the unworthiness they fear in themselves onto others, believing they are better than others and treating them with contempt.</p>


