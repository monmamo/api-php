<h1>One: The Reformer, the Idealist, the Perfectionist</h1>

<p>Ones are conscientious and ethical, with a strong sense of right and wrong. They are teachers, crusaders, and advocates for change: always striving to improve things, but afraid of making a mistake. Well-organized, orderly, and fastidious, they try to maintain high standards, but can slip into being critical and perfectionistic. They typically have problems with resentment and impatience. At their best, Ones are wise, discerning, realistic, and noble. They can be morally heroic. </p>

    <ul>
        <li>Basic Fear: Of being corrupt/evil, defective</li>   
<li>Basic Desire: To be good, to have integrity, to be balanced.</li> 
    </ul>

<h2>Positive Arc: Resentment to Integrity</h2>



<p>Type Ones at their best represent responsibility and idealism. At their worst, they come across as judgmental and obsessive. Their core vice (or “passion“) is an under-the-surface resentment, born out of their frustration that their attempts to make a better world are stymied and/or unappreciated.</p>

<p>The deep-seated Lie of their personality is fueled by an unconscious fear of their own badness or defectiveness. Their arc challenges them to come into true integrity by claiming all parts of themselves, recognizing the good not just in themselves but in the world around them. They offer the gift of being able to improve the world for themselves and others. When done from a place of love, this enables them to find a higher purpose.</p>

<h2>Negative Arc:  Resentment to Tyranny</h2>

<p>Type Ones’ native desire to bring integrity to themselves and the world around them can become complicated by an unconscious fear that they are, in fact, inherently bad or corrupt in some way. This pushes these characters toward perfectionism, first in small ways, and then, if unchecked, into an obsessive tyranny that desires to control others as well. An early sign this character may be at the beginning of an arc (whether positive or negative) is their tendency to judge or condemn both themselves and others.</p>

<p>This may lead them further into the Lie that they are personally responsible or obligated to fix “everything.” If these tendencies are left unchecked, Ones may begin manipulating others by offering “correction” that attempts to bring others into line with their own personal beliefs and standards. In cases of extreme unhealth, they may end up projecting all the “badness” they fear in themselves onto others and taking it upon themselves to mete out punishment.</p>


